function TextFileViewer({
  filePath,
  cwd,
  sourceSessionId,
  onOpenFile,
  onMentionLines,
  onAtMention,
  gitRefreshKey,
  initialDisplayMode,
  initialLineTarget,
  initialState: restoredState,
  onStateChange,
  initialDraft,
  savePending,
  onDraftChange,
  onSavingChange,
  watchEnabled = true,
}: Props) {
  // These are restoration inputs, not a controlled viewer state. Later reports
  // must not reset the live viewer while preserving preferences for a new link.
  const initialState = useRef(restoredState).current;
  const { isDark } = useTheme();
  const { t } = useI18n();
  const [data, setData] = useState<FileData | null>(null);
  const [gitDiff, setGitDiff] = useState<GitFileDiffResponse | null>(null);
  const workingRevision = gitDiff?.revision;
  const comparison = `${filePath}:${workingRevision ?? ""}`;
  const workingPatch = gitDiff?.patch;
  const diffReview = useMemo(() => workingPatch ? createDiffReview(workingPatch, comparison) : undefined, [workingPatch, comparison]);
  const loadWorkingContext = useCallback(async (signal: AbortSignal): Promise<DiffContext> => {
    const params = new URLSearchParams({ cwd: cwd!, path: filePath, op: "context", revision: workingRevision! });
    const response = await fetch(`/api/git/diff?${params}`, { signal, cache: "no-store" });
    const body = await response.json();
    if (!response.ok) throw new Error(body.error ?? "Full-file context unavailable; refresh the diff.");
    return body;
  }, [cwd, filePath, workingRevision]);
  const [gitDiffLoading, setGitDiffLoading] = useState(false);
  const [gitDiffResolved, setGitDiffResolved] = useState(false);
  const [loading, setLoading] = useState(true);
  const [loadingMore, setLoadingMore] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const requestedInitialDisplayMode = resolveInitialFileDisplayMode(initialState, initialDisplayMode);
  const initialWrapLines = initialState?.wrapLines ?? false;
  const initialScrollTop = initialState?.scrollTop ?? 0;
  const initialScrollLeft = initialState?.scrollLeft ?? 0;
  const [displayMode, setDisplayMode] = useState<DisplayMode>(requestedInitialDisplayMode);
  const [wrapLines, setWrapLines] = useState(initialWrapLines);
  const [watching, setWatching] = useState(false);
  const esRef = useRef<EventSource | null>(null);
  const contentRequestRef = useRef(0);
  const gitDiffRequestRef = useRef(0);
  const contentRef = useRef<HTMLDivElement | null>(null);
  const autoDiffAppliedRef = useRef(false);
  const defaultPreviewEligibleRef = useRef(
    initialState === undefined && initialDisplayMode === undefined,
  );
  const scrollRestorePendingRef = useRef(true);
  const navigatedModeRef = useRef<string | undefined>(undefined);
  const previewNavigationAttemptedRef = useRef(false);
  const lineTargetHandledRef = useRef(false);
  const targetLoadOffsetRef = useRef<number | undefined>(undefined);
  const viewerStateRef = useRef<FileViewerState>({
    displayMode: requestedInitialDisplayMode,
    wrapLines: initialWrapLines,
    scrollTop: initialScrollTop,
    scrollLeft: initialScrollLeft,
  });
  const onStateChangeRef = useRef(onStateChange);
  const [selectedLineRange, setSelectedLineRange] = useState<SelectedLineRange | null>(null);
  const [editSnapshot, setEditSnapshot] = useState<{ content: string; revision: string; writable: boolean } | null>(
    initialDraft ? { content: initialDraft.baseline, revision: initialDraft.revision, writable: true } : null,
  );
  const [draft, setDraft] = useState<FileEditDraft | undefined>(initialDraft);
  const draftRef = useRef(draft);
  const onDraftChangeRef = useRef(onDraftChange);
  onDraftChangeRef.current = onDraftChange;
  const onSavingChangeRef = useRef(onSavingChange);
  onSavingChangeRef.current = onSavingChange;
  const [editing, setEditing] = useState(Boolean(!initialLineTarget && initialDraft && initialDraft.content !== initialDraft.baseline));
  const [saving, setSaving] = useState(false);
  const savingElsewhere = Boolean(savePending && !saving);
  const [saveError, setSaveError] = useState<string | null>(null);
  const [externalChange, setExternalChange] = useState(false);
  const editRequestRef = useRef(0);
  const dirty = Boolean(draft && draft.content !== draft.baseline);
  draftRef.current = draft;

  const setFileDraft = useCallback((next: FileEditDraft | undefined) => {
    draftRef.current = next;
    setDraft(next);
    onDraftChangeRef.current?.(next);
  }, []);

  onStateChangeRef.current = onStateChange;

  const updateDisplayMode = useCallback((nextDisplayMode: DisplayMode) => {
    viewerStateRef.current.displayMode = nextDisplayMode;
    setDisplayMode(nextDisplayMode);
    onStateChangeRef.current?.({ ...viewerStateRef.current });
  }, []);

  const toggleWrapLines = useCallback(() => {
    const next = !wrapLines;
    viewerStateRef.current.wrapLines = next;
    setWrapLines(next);
    onStateChangeRef.current?.({ ...viewerStateRef.current });
  }, [wrapLines]);

  useEffect(() => {
    const nextState: FileViewerState = {
      displayMode: requestedInitialDisplayMode,
      wrapLines: initialWrapLines,
      scrollTop: initialScrollTop,
      scrollLeft: initialScrollLeft,
    };

    viewerStateRef.current = nextState;
    scrollRestorePendingRef.current = true;
    autoDiffAppliedRef.current = false;
    setDisplayMode(requestedInitialDisplayMode);
    setWrapLines(initialWrapLines);

    return () => {
      onStateChangeRef.current?.({ ...viewerStateRef.current }, lineTargetHandledRef.current);
    };
  }, [
    filePath,
    sourceSessionId,
    requestedInitialDisplayMode,
    initialWrapLines,
    initialScrollTop,
    initialScrollLeft,
  ]);

  const fetchContent = useCallback((filePath: string, offset = 0) => {
    const requestId = ++contentRequestRef.current;
    return fetch(getFileApiUrl(filePath, "read", sourceSessionId, { offset: offset || undefined }))
      .then((r) => r.json())
      .then((d: FileData & { error?: string }) => {
        if (requestId !== contentRequestRef.current) return null;
        if (d.error) {
          setError(d.error);
          return null;
        }
        setError(null);
        setData((current) => offset && current
          ? { ...d, content: current.content + d.content }
          : d);
        return d;
      })
      .catch((e) => {
        if (requestId !== contentRequestRef.current) return null;
        setError(String(e));
        return null;
      });
  }, [sourceSessionId]);

  const fetchEditable = useCallback(async (targetPath: string) => {
    const requestId = ++editRequestRef.current;
    try {
      const response = await fetch(getFileApiUrl(targetPath, "edit", sourceSessionId));
      const next = await response.json() as { content?: string; revision?: string; writable?: boolean };
      if (requestId !== editRequestRef.current) return;
      if (!response.ok || typeof next.content !== "string" || typeof next.revision !== "string") {
        if (draftRef.current && draftRef.current.content !== draftRef.current.baseline) setExternalChange(true);
        else setEditSnapshot(null);
        return;
      }
      const currentDraft = draftRef.current;
      setEditSnapshot({ content: next.content, revision: next.revision, writable: next.writable === true });
      if (currentDraft && currentDraft.content !== currentDraft.baseline) {
        setExternalChange(next.revision !== currentDraft.revision);
      } else {
        if (currentDraft) setFileDraft(undefined);
        setExternalChange(false);
      }
    } catch {
      if (requestId === editRequestRef.current) {
        if (draftRef.current && draftRef.current.content !== draftRef.current.baseline) setExternalChange(true);
        else setEditSnapshot(null);
      }
    }
  }, [sourceSessionId, setFileDraft]);

  const fetchGitDiff = useCallback(async (targetPath: string) => {
    const requestId = ++gitDiffRequestRef.current;
    setGitDiffLoading(true);
    if (!cwd) {
      setGitDiff(null);
      setGitDiffLoading(false);
      setGitDiffResolved(true);
      return;
    }

    try {
      const params = new URLSearchParams({ cwd, path: targetPath });
      const response = await fetch(`/api/git/diff?${params.toString()}`);
      const next = await response.json() as GitFileDiffResponse & { error?: string };
      if (requestId !== gitDiffRequestRef.current) return;
      setGitDiff(response.ok && next.supported && typeof next.patch === "string" ? next : null);
    } catch {
      if (requestId === gitDiffRequestRef.current) setGitDiff(null);
    } finally {
      if (requestId === gitDiffRequestRef.current) {
        setGitDiffLoading(false);
        setGitDiffResolved(true);
      }
    }
  }, [cwd]);

  const saveDraft = useCallback(async () => {
    const current = draftRef.current;
    if (!current || current.content === current.baseline || saving || savingElsewhere) return;
    setSaving(true);
    onSavingChangeRef.current?.(true);
    setSaveError(null);
    try {
      const response = await fetch(getFileApiUrl(filePath, "save", sourceSessionId), {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ content: current.content, expectedRevision: current.revision }),
      });
      const result = await response.json() as { revision?: string; error?: string };
      if (!response.ok || !result.revision) {
        if (response.status === 409) setExternalChange(true);
        setSaveError(result.error ?? "Could not save file");
        return;
      }
      setEditSnapshot({ content: current.content, revision: result.revision, writable: true });
      // Keep keystrokes typed during the request as a new draft.
      const latest = draftRef.current;
      setFileDraft(latest && latest.content !== current.content
        ? { content: latest.content, baseline: current.content, revision: result.revision }
        : undefined);
      setExternalChange(false);
      void fetchContent(filePath);
      void fetchGitDiff(filePath);
    } catch (error) {
      setSaveError(error instanceof Error ? error.message : String(error));
    } finally {
      setSaving(false);
      onSavingChangeRef.current?.(false);
    }
  }, [filePath, sourceSessionId, saving, savingElsewhere, setFileDraft, fetchContent, fetchGitDiff]);

  // Reset and load the file itself when its identity changes. Live watching is
  // managed separately so pausing it never clears the displayed content.
  useEffect(() => {
    let active = true;
    setLoading(true);
    setError(null);
    setData(null);
    setGitDiff(null);
    setGitDiffResolved(false);
    setWatching(false);
    void fetchEditable(filePath);

    fetchContent(filePath).finally(() => {
      if (active) setLoading(false);
    });

    return () => {
      active = false;
    };
  }, [filePath, fetchContent, fetchEditable, sourceSessionId]);

  useEffect(() => {
    setWatching(false);

    if (esRef.current) {
      esRef.current.close();
      esRef.current = null;
    }

    if (!watchEnabled) return;

    const synchronize = () => {
      if (!draftRef.current || draftRef.current.content === draftRef.current.baseline) void fetchContent(filePath);
      void fetchEditable(filePath);
      void fetchGitDiff(filePath);
    };

    const es = new EventSource(getFileApiUrl(filePath, "watch", sourceSessionId));
    esRef.current = es;

    es.addEventListener("connected", () => {
      setWatching(true);
      // The server emits connected only after its watcher exists. Reading now
      // closes the gap between the last snapshot and live events.
      synchronize();
    });

    es.addEventListener("change", synchronize);

    const markDisconnected = () => {
      setWatching(false);
    };
    es.addEventListener("error", markDisconnected);
    es.onerror = markDisconnected;

    return () => {
      es.close();
      if (esRef.current === es) esRef.current = null;
    };
  }, [filePath, fetchContent, fetchEditable, fetchGitDiff, sourceSessionId, watchEnabled]);

  useEffect(() => {
    void fetchGitDiff(filePath);
  }, [fetchGitDiff, filePath, gitRefreshKey]);

  useEffect(() => {
    // HTML gets the same rendered-first treatment as markdown: a generated page
    // is usually more useful viewed than read as source. Both have a preview
    // mode already; the source tab stays one click away. A restored choice or
    // explicit mode hint always wins over this default.
    if (
      defaultPreviewEligibleRef.current
      && !data?.truncated
      && (data?.language === "markdown" || data?.language === "html")
    ) {
      defaultPreviewEligibleRef.current = false;
      updateDisplayMode("preview");
    }
  }, [data?.language, data?.truncated, updateDisplayMode]);

  useEffect(() => {
    // Line targets refer to the current file, not a diff or HTML iframe.
    if (initialLineTarget && !lineTargetHandledRef.current && (displayMode === "diff" || (data?.language === "html" && displayMode === "preview"))) {
      updateDisplayMode("source");
    }
  }, [initialLineTarget, displayMode, data?.language, updateDisplayMode]);

  const hasGitDiff = gitDiff?.supported === true && typeof gitDiff.patch === "string";
  const isDeletedDiff = hasGitDiff && gitDiff.status === "deleted";

  useEffect(() => {
    if (gitDiffResolved && !hasGitDiff && displayMode === "diff") updateDisplayMode("source");
  }, [displayMode, gitDiffResolved, hasGitDiff, updateDisplayMode]);

  // Wait for the git request before restoring diff mode so the unresolved
  // placeholder cannot immediately demote it back to source.
  useEffect(() => {
    if (!initialLineTarget && requestedInitialDisplayMode === "diff" && hasGitDiff && !autoDiffAppliedRef.current) {
      autoDiffAppliedRef.current = true;
      updateDisplayMode("diff");
    }
  }, [initialLineTarget, requestedInitialDisplayMode, hasGitDiff, updateDisplayMode]);

  const viewerContent = dirty && (!initialLineTarget || editing) ? draft!.content : data?.content ?? "";
  const markdownPreview = useMemo(
    () => normalizeDisplayMathWithSourceMap(data?.language === "markdown" ? viewerContent : ""),
    [data?.language, viewerContent],
  );
  const positionedMarkdownPlugins = useMemo<ComponentProps<typeof ReactMarkdown>["rehypePlugins"]>(
    // Insert positions after sanitization but before KaTeX replaces math nodes.
    () => [...(markdownPreviewRehypePlugins ?? []).slice(0, -1),
      [rehypeMarkdownSourceLines, { sourceLines: markdownPreview.sourceLines }],
      ...(markdownPreviewRehypePlugins ?? []).slice(-1)],
    [markdownPreview.sourceLines],
  );

  const frontmatter = useMemo(
    () => (data?.language === "markdown" ? parseFrontmatter(viewerContent) : null),
    [data?.language, viewerContent],
  );

  const sourceLines = useMemo(() => viewerContent.split("\n"), [viewerContent]);
  const language = data?.language ?? "text";
  const isHtml = language === "html";
  const isMarkdown = language === "markdown";
  const hasPreview = !data?.truncated && (isHtml || isMarkdown);
  const effectiveDisplayMode = isDeletedDiff ? "diff" : displayMode;
  const useLightweightSource = sourceLines.length > SOURCE_HIGHLIGHT_MAX_LINES
    && !(effectiveDisplayMode === "diff" && hasGitDiff)
    && !(effectiveDisplayMode === "preview" && hasPreview);
  // react-syntax-highlighter rebuilds every token element on each render, which
  // costs hundreds of milliseconds on large files. Cache the rendered trees so
  // unrelated re-renders (panel open/close, selection changes) reuse them as-is.
  const highlightedSource = useMemo(
    () => (
      <SyntaxHighlighter
        className={wrapLines ? "file-source-view is-wrapped" : "file-source-view"}
        language={language === "text" ? "plaintext" : language}
        style={isDark ? vscDarkPlus : vs}
        showLineNumbers
        lineNumberStyle={{
          ...FILE_LINE_NUMBER_STYLE,
        }}
        customStyle={{
          margin: 0,
          padding: 0,
          border: 0,
          // Override both Prism theme forms without mixing CSS declarations.
          background: undefined,
          backgroundColor: "var(--bg)",
          ...FILE_CODE_STYLE,
          width: wrapLines ? "100%" : "max-content",
          minWidth: "100%",
          minHeight: "100%",
          overflow: "visible",
        }}
        codeTagProps={{
          style: {
            fontFamily: "var(--font-mono)",
            overflowWrap: wrapLines ? "anywhere" : "normal",
          },
        }}
        renderer={(rendererProps) => (
          <SourceCodeRenderer {...rendererProps} wrapLines={wrapLines} />
        )}
        wrapLongLines={wrapLines}
      >
        {viewerContent}
      </SyntaxHighlighter>
    ),
    [isDark, language, viewerContent, wrapLines],
  );
  const lightweightSourceLines = useMemo(
    () => useLightweightSource ? sourceLines.map((line, lineIndex) => (
      <span
        className="file-source-line"
        data-line-number={lineIndex + 1}
        key={`source-line-${lineIndex}`}
        style={{ display: "flex", minWidth: "100%" }}
      >
        <span aria-hidden="true" style={FILE_LINE_NUMBER_STYLE}>
          {lineIndex + 1}
        </span>
        <span
          className="file-source-line-content"
          style={{
            flex: "1 1 auto",
            minWidth: 0,
            overflowWrap: wrapLines ? "anywhere" : "normal",
            whiteSpace: wrapLines ? "pre-wrap" : "pre",
          }}
        >
          {line}
        </span>
      </span>
    )) : null,
    [sourceLines, useLightweightSource, wrapLines],
  );

  useEffect(() => {
    const updateSelectedLineRange = () => {
      const root = contentRef.current;
      setSelectedLineRange((current) => {
        const next = onMentionLines && displayMode === "source" && root
          ? getSelectedSourceLineRange(root, window.getSelection())
          : null;
        // Skip no-op updates: selectionchange fires continuously while dragging,
        // and a fresh-but-equal range object would re-render the whole viewer.
        if (current === null && next === null) return current;
        if (current && next && current.startLine === next.startLine && current.endLine === next.endLine) return current;
        return next;
      });
    };

    updateSelectedLineRange();
    if (!onMentionLines || displayMode !== "source") return;

    document.addEventListener("selectionchange", updateSelectedLineRange);
    return () => document.removeEventListener("selectionchange", updateSelectedLineRange);
  }, [data?.content, displayMode, onMentionLines]);

  const mentionLineRange = useCallback((lineRange: SelectedLineRange | null) => {
    if (!onMentionLines || !lineRange) return;
    onMentionLines(
      getRelativeFilePath(filePath, cwd),
      lineRange.startLine,
      lineRange.endLine,
    );
  }, [cwd, filePath, onMentionLines]);

  useEffect(() => {
    if (!onMentionLines || displayMode !== "source") return;

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.repeat || event.key.toLowerCase() !== "i" || (!event.metaKey && !event.ctrlKey) || event.altKey || event.shiftKey) return;

      const target = event.target;
      if (target instanceof Element && target.closest("input, textarea, [contenteditable='true']")) return;

      const root = contentRef.current;
      const lineRange = root ? getSelectedSourceLineRange(root, window.getSelection()) : null;
      if (!lineRange) return;

      event.preventDefault();
      mentionLineRange(lineRange);
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [displayMode, mentionLineRange, onMentionLines]);

  useEffect(() => {
    if (!scrollRestorePendingRef.current || loading) return;
    if (error && !isDeletedDiff) return;
    if (requestedInitialDisplayMode === "diff" && !gitDiffResolved) return;
    if (requestedInitialDisplayMode === "diff" && hasGitDiff && displayMode !== "diff") return;

    const content = contentRef.current;
    if (!content) return;

    content.scrollTop = viewerStateRef.current.scrollTop;
    content.scrollLeft = viewerStateRef.current.scrollLeft;
    scrollRestorePendingRef.current = false;
  }, [
    data?.content,
    displayMode,
    error,
    gitDiffResolved,
    hasGitDiff,
    isDeletedDiff,
    loading,
    requestedInitialDisplayMode,
  ]);

  useEffect(() => {
    if (editing || (effectiveDisplayMode !== "source" && !(isMarkdown && effectiveDisplayMode === "preview"))) {
      navigatedModeRef.current = undefined;
      return;
    }
    if (!initialLineTarget || loading || error || !data || isDeletedDiff) return;
    // Load successive bounded chunks only when needed to reach the requested line.
    if (data.truncated && (initialLineTarget.endLine ?? initialLineTarget.line) >= sourceLines.length) {
      if (!loadingMore && targetLoadOffsetRef.current !== data.nextOffset) {
        targetLoadOffsetRef.current = data.nextOffset;
        setLoadingMore(true);
        void fetchContent(filePath, data.nextOffset).finally(() => {
          targetLoadOffsetRef.current = undefined;
          setLoadingMore(false);
        });
      }
      return;
    }
    // On first open, wait for rendered-first Markdown instead of consuming a
    // transient source render before the default-preview effect settles.
    if (isMarkdown && hasPreview && effectiveDisplayMode === "source" && !initialState
      && !initialDisplayMode && !previewNavigationAttemptedRef.current) return;
    if (effectiveDisplayMode === "preview") previewNavigationAttemptedRef.current = true;
    const root = contentRef.current;
    if (!root || navigatedModeRef.current === effectiveDisplayMode) return;
    // Missing/stale locations are not silently relabeled as the last line.
    if (initialLineTarget.line > sourceLines.length) {
      lineTargetHandledRef.current = true;
      return;
    }
    if (navigateToFileLine(root, initialLineTarget, effectiveDisplayMode === "preview")) {
      navigatedModeRef.current = effectiveDisplayMode;
      lineTargetHandledRef.current = true;
      scrollRestorePendingRef.current = false;
      viewerStateRef.current.scrollTop = root.scrollTop;
      viewerStateRef.current.scrollLeft = root.scrollLeft;
    } else if (effectiveDisplayMode === "preview") {
      // A document containing only hidden markup has no rendered block to target.
      updateDisplayMode("source");
    }
  }, [initialLineTarget, loading, error, editing, data, isDeletedDiff, effectiveDisplayMode, isMarkdown, hasPreview, initialState, initialDisplayMode, sourceLines.length, loadingMore, fetchContent, filePath, updateDisplayMode]);

  if (loading || (requestedInitialDisplayMode === "diff" && gitDiffLoading && !data)) {
    return (
      <div style={{ height: "100%", display: "flex", alignItems: "center", justifyContent: "center", color: "var(--text-muted)", fontSize: 13 }}>
        {t("i18n.loading")}
      </div>
    );
  }

  if (error && !isDeletedDiff && !dirty) {
    return (
      <div style={{ height: "100%", display: "flex", alignItems: "center", justifyContent: "center", color: "#f87171", fontSize: 13 }}>
        {error}
      </div>
    );
  }

  if (!data && !isDeletedDiff && !dirty) return null;

  const content = viewerContent;
  const markdownDirectory = getFileDirectory(filePath);
  const lines = sourceLines;
  const displayModes: DisplayMode[] = isDeletedDiff
    ? ["diff"]
    : [
        "source",
        ...(hasPreview ? ["preview" as const] : []),
        ...(hasGitDiff ? ["diff" as const] : []),
      ];
  const metadata = isDeletedDiff
    ? t("files.deleted")
    : `${language} · ${lines.length} lines · ${formatSize(data?.size ?? 0)}`;

  return (
    <div className="file-viewer-shell" style={{ display: "flex", flexDirection: "column", height: "100%", overflow: "hidden", position: "relative" }}>
      <div
        className="file-viewer-toolbar"
        style={{
          display: "flex",
          alignItems: "center",
          gap: 8,
          padding: "5px 12px",
          borderBottom: "1px solid var(--border)",
          fontSize: 11,
          color: "var(--text-dim)",
          background: "var(--bg)",
          flexShrink: 0,
        }}
      >
        <span className="file-viewer-path" style={{ fontFamily: "var(--font-mono)" }} title={filePath}>
          {getRelativeFilePath(filePath, cwd)}
        </span>

        <span className="file-viewer-meta" title={metadata}>{metadata}</span>
        {!isDeletedDiff && (
          <span
            title={watching ? t("i18n.liveSync") : t("i18n.notWatching")}
            aria-label={watching ? t("i18n.liveSync") : t("i18n.notWatching")}
            className="file-viewer-live-indicator"
            style={{
              background: watching ? "#4ade80" : "var(--border)",
              boxShadow: watching ? "0 0 4px #4ade80" : "none",
            }}
          />
        )}

        <div className="file-viewer-controls">
          {displayModes.length > 1 && (
            <div className="file-viewer-mode-switch" aria-label={t("i18n.fileViewMode")}>
              {displayModes.map((mode) => {
                const active = effectiveDisplayMode === mode;
                return (
                  <button
                    key={mode}
                    type="button"
                    onClick={() => updateDisplayMode(mode)}
                    title={mode === "diff" ? t("i18n.compareHead") : undefined}
                    aria-pressed={active}
                    className="file-viewer-mode-button"
                    style={{
                      background: active ? "var(--bg-selected)" : "transparent",
                      color: active ? "var(--text)" : "var(--text-muted)",
                    }}
                  >
                    {DISPLAY_MODE_LABELS[mode]}
                  </button>
                );
              })}
            </div>
          )}

          <div className="file-viewer-actions">
            {(editSnapshot?.writable || dirty) && !isDeletedDiff && (
              <>
                <button type="button" className="file-viewer-mode-button" aria-pressed={editing} disabled={savingElsewhere}
                  onClick={() => setEditing((value) => !value)}>{t("files.edit")}</button>
                {dirty && <button type="button" className="file-viewer-mode-button"
                  disabled={saving || savingElsewhere || externalChange || !editSnapshot?.writable} onClick={() => void saveDraft()}>{saving ? t("files.saving") : t("i18n.save")}</button>}
              </>
            )}
            {(onAtMention || onMentionLines) && (
              <button
                type="button"
                onPointerDown={(event) => event.preventDefault()}
                onClick={() => {
                  // Mention selected lines when a range is active (and line
                  // mention is wired up); otherwise fall back to a whole-file
                  // @mention. Same button, behavior follows the selection.
                  if (selectedLineRange && onMentionLines) {
                    mentionLineRange(selectedLineRange);
                  } else {
                    onAtMention?.(getRelativeFilePath(filePath, cwd), false);
                  }
                }}
                title={
                  selectedLineRange && onMentionLines
                    ? `${t("i18n.mentionSelectedLines")} (L${selectedLineRange.startLine}${selectedLineRange.startLine !== selectedLineRange.endLine ? `-L${selectedLineRange.endLine}` : ""})`
                    : t("files.insertPath")
                }
                aria-label={t("files.mention")}
                disabled={!onAtMention && !onMentionLines}
                className="file-viewer-icon-button"
              >
                <MentionIcon />
              </button>
            )}
            {effectiveDisplayMode === "source" && (
              <>
                <button
                  type="button"
                  onClick={toggleWrapLines}
                  title={wrapLines ? t("i18n.disableWrap") : t("i18n.enableWrap")}
                  aria-label={wrapLines ? t("i18n.disableWrap") : t("i18n.enableWrap")}
                  aria-pressed={wrapLines}
                  className="file-viewer-icon-button"
                  style={{
                    background: wrapLines ? "var(--bg-selected)" : "transparent",
                    color: wrapLines ? "var(--text)" : "var(--text-muted)",
                  }}
                >
                  <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                    <path d="M3 6h18" />
                    <path d="M3 12h15a3 3 0 1 1 0 6h-4" />
                    <path d="m16 16-2 2 2 2" />
                    <path d="M3 18h7" />
                  </svg>
                </button>
              </>
            )}
          </div>

          {!isDeletedDiff && <DownloadLink filePath={filePath} sourceSessionId={sourceSessionId} />}
        </div>
      </div>

      {savingElsewhere && <div role="status" style={{ padding: "6px 12px", fontSize: 12, color: "var(--text-muted)" }}>{t("files.savePending")}</div>}
      {(dirty || externalChange || saveError) && (
        <div role="status" style={{ padding: "6px 12px", fontSize: 12, color: externalChange || saveError ? "#f87171" : "var(--text-muted)" }}>
          {externalChange ? t("files.editConflict") : saveError ?? t("files.unsaved")}
          {externalChange && <button type="button" className="file-viewer-mode-button" disabled={savingElsewhere} onClick={() => {
            if (!window.confirm(t("files.discardConfirm"))) return;
            setFileDraft(undefined);
            setSaveError(null);
            setExternalChange(false);
            void fetchContent(filePath);
            void fetchEditable(filePath);
          }}>{t("files.discard")}</button>}
        </div>
      )}
      {data?.truncated && (
        <div
          className="file-viewer-load-more"
          style={{
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            gap: 10,
            padding: "5px 8px",
            border: "1px solid var(--border)",
            borderRadius: 6,
            color: "var(--text-dim)",
            fontSize: 11,
          }}
        >
          <span>{formatSize(data.nextOffset)} / {formatSize(data.size)}</span>
          <button
            type="button"
            className="file-viewer-mode-button"
            disabled={loadingMore}
            onClick={() => {
              setLoadingMore(true);
              void fetchContent(filePath, data.nextOffset).finally(() => setLoadingMore(false));
            }}
          >
            {loadingMore ? t("i18n.loading") : t("i18n.loadMore")}
          </button>
        </div>
      )}

      {initialLineTarget && dirty && !editing && (
        <div role="status" style={{ padding: "8px 12px", color: "var(--text-muted)", fontSize: 12 }}>{t("files.savedLineTarget")}</div>
      )}
      {initialLineTarget && !loading && !editing && initialLineTarget.line > sourceLines.length && (
        <div role="status" style={{ padding: "8px 12px", color: "var(--text-muted)", fontSize: 12 }}>
          {data?.truncated
            ? t("files.loadingLine", { line: initialLineTarget.line })
            : t("files.lineUnavailable", { line: initialLineTarget.line, count: sourceLines.length })}
        </div>
      )}

      {/* Content area */}
      <div
        ref={contentRef}
        className="file-viewer-content"
        onScroll={(event) => {
          viewerStateRef.current.scrollTop = event.currentTarget.scrollTop;
          viewerStateRef.current.scrollLeft = event.currentTarget.scrollLeft;
        }}
        style={{ flex: 1, overflow: "auto", background: "var(--bg)", paddingBottom: data?.truncated ? 48 : undefined }}
      >
        {editing && editSnapshot && !isDeletedDiff ? (
          <textarea
            aria-label={t("files.edit")}
            readOnly={savingElsewhere}
            value={draft?.content ?? editSnapshot.content}
            onChange={(event) => {
              if (savingElsewhere) return;
              const baseline = draft?.baseline ?? editSnapshot.content;
              const revision = draft?.revision ?? editSnapshot.revision;
              setFileDraft({ content: event.target.value, baseline, revision });
              setSaveError(null);
            }}
            onKeyDown={(event) => {
              if (savingElsewhere) return;
              if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === "s") {
                event.preventDefault();
                if (!externalChange && editSnapshot.writable) void saveDraft();
              }
              if (event.key === "Tab") {
                event.preventDefault();
                const field = event.currentTarget;
                const start = field.selectionStart;
                const next = field.value.slice(0, start) + "\t" + field.value.slice(field.selectionEnd);
                setFileDraft({ content: next, baseline: draft?.baseline ?? editSnapshot.content, revision: draft?.revision ?? editSnapshot.revision });
                requestAnimationFrame(() => { field.selectionStart = field.selectionEnd = start + 1; });
              }
            }}
            spellCheck={false}
            style={{ boxSizing: "border-box", width: "100%", minHeight: "100%", padding: "12px 16px", resize: "none", border: "none", outline: "none", background: "var(--bg)", color: "var(--text)", ...FILE_CODE_STYLE, tabSize: 2 }}
          />
        ) : effectiveDisplayMode === "diff" && hasGitDiff ? (
          <CommittedPatchDiff key={`${filePath}:${gitDiff.revision ?? gitDiff.patch}`} patch={gitDiff.patch!} hasBinaryChanges={false}
            before="HEAD" after="Working tree" reviewModel={diffReview} loadContext={gitDiff.revision ? loadWorkingContext : undefined}
            onRefresh={() => void fetchGitDiff(filePath)} />
        ) : isHtml && effectiveDisplayMode === "preview" ? (
          <iframe
            srcDoc={content}
            sandbox="allow-scripts"
            style={{ width: "100%", height: "100%", border: "none", background: "var(--bg)" }}
             title={t("i18n.htmlPreview")}
          />
        ) : isMarkdown && effectiveDisplayMode === "preview" ? (
          <div
            className="markdown-body markdown-file-preview"
            style={{ padding: "24px 32px" }}
          >
            {frontmatter?.data && <div data-source-line-start={1} data-source-line-end={viewerContent.slice(0, viewerContent.length - frontmatter.rest.length).split(/\r?\n/).length - 1}>
              <FrontmatterCard data={frontmatter.data} />
            </div>}
            <MarkdownPreviewLinkContext.Provider value={{ baseDir: markdownDirectory, relativeRoot: cwd ?? markdownDirectory, onOpenFile }}>
            <ReactMarkdown
              remarkPlugins={markdownPreviewRemarkPlugins}
              rehypePlugins={positionedMarkdownPlugins}
              urlTransform={onOpenFile ? markdownUrlTransform : undefined}
              components={{
                ...markdownCodeComponents,
                a: MarkdownPreviewLink,
                img({ src, alt, ...props }) {
                  delete props.node;
                  const imagePath = typeof src === "string"
                    ? resolveLocalFileHref(src, markdownDirectory, cwd ?? markdownDirectory)
                    : null;
                  const imageSrc = imagePath
                    ? getFileApiUrl(imagePath, "read", sourceSessionId)
                    : src;
                  // Dynamic local paths are served directly by the file API.
                  // eslint-disable-next-line @next/next/no-img-element
                  return <img src={imageSrc} alt={alt ?? ""} loading="lazy" {...props} />;
                },
              }}
            >
              {markdownPreview.markdown}
            </ReactMarkdown>
            </MarkdownPreviewLinkContext.Provider>
          </div>
        ) : useLightweightSource ? (
          <div
            className="file-source-view is-lightweight"
            style={{
              width: wrapLines ? "100%" : "max-content",
              minWidth: "100%",
              minHeight: "100%",
              background: "var(--bg)",
              ...FILE_CODE_STYLE,
            }}
          >
            {lightweightSourceLines}
          </div>
        ) : (
          highlightedSource
        )}
      </div>
    </div>
  );
}
