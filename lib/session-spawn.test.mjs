import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url);
const { readSessionSpawn, sessionSpawnFromEntries } = await jiti.import("./session-spawn.ts");
const { scanSessionFileInfo, listSessionsIncremental } = await jiti.import("./session-list-scanner.ts");
const ID = "22222222-2222-4222-8222-222222222222", CREATOR = "11111111-1111-4111-8111-111111111111";
const data = { version: 1, sessionId: ID, creatorSessionId: CREATOR, operationId: "33333333-3333-4333-8333-333333333333" };
test("spawn metadata applies only to the original created ID, never copied fork/clone entries", () => {
  assert.deepEqual(readSessionSpawn(data, ID), data);
  assert.equal(readSessionSpawn(data, "fork-id"), null);
  assert.equal(readSessionSpawn({ ...data, creatorSessionId: ID }, ID), null);
  assert.equal(readSessionSpawn({ ...data, creatorSessionId: "../path" }, ID), null);
  assert.equal(readSessionSpawn({ ...data, version: 99 }, ID), null);
  const entries = [{ type: "custom", customType: "pi-web:session-spawn", data }];
  assert.deepEqual(sessionSpawnFromEntries(entries, ID), data);
  assert.equal(sessionSpawnFromEntries(entries, "clone-id"), null);
});
test("scanner persists creator ID independently of parent paths and rehydrates it from saved index", async (t) => {
  const root = mkdtempSync(join(tmpdir(), "pi-spawn-scan-")), previous = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = root;
  t.after(() => { if (previous === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previous; rmSync(root, { recursive: true, force: true }); globalThis.__piWebScanIndex = undefined; globalThis.__piWebScanIndexLoaded = undefined; });
  globalThis.__piWebScanIndex = undefined; globalThis.__piWebScanIndexLoaded = undefined;
  const directory = join(root, "sessions", "project"); mkdirSync(directory, { recursive: true });
  const file = join(directory, "2026-10-18T00-00-00-000Z_" + ID + ".jsonl");
  const header = { type: "session", version: 3, id: ID, timestamp: "2026-10-18T00:00:00Z", cwd: root };
  const entry = { type: "custom", id: "spawn", parentId: null, timestamp: header.timestamp, customType: "pi-web:session-spawn", data };
  writeFileSync(file, [header, entry].map(JSON.stringify).join("\n") + "\n");
  assert.equal((await scanSessionFileInfo(file)).spawnedBy, CREATOR);
  assert.equal((await listSessionsIncremental())[0].spawnedBy, CREATOR);
  await new Promise((resolve) => setImmediate(resolve));
  globalThis.__piWebScanIndex = undefined; globalThis.__piWebScanIndexLoaded = undefined;
  assert.equal((await listSessionsIncremental())[0].spawnedBy, CREATOR, "saved-index reload preserves marker");
  const fork = join(directory, "2026-10-18T00-00-00-000Z_fork-id.jsonl");
  writeFileSync(fork, [{ ...header, id: "fork-id", parentSession: file }, entry].map(JSON.stringify).join("\n") + "\n");
  assert.equal((await scanSessionFileInfo(fork)).spawnedBy, undefined);
});
