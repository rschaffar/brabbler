import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, statSync, rmSync, symlinkSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { createJiti } from "jiti";
import { execFileSync } from "node:child_process";
const jiti = createJiti(import.meta.url, { fsCache: false });
const { scratchpadPath, scratchpadProject, readScratchpad, saveScratchpad, ScratchpadConflict } = await jiti.import("./scratchpad-server.ts");
const { SCRATCHPAD_MAX_LENGTH } = await jiti.import("./scratchpad.ts");
const { trustedGitRepository } = await jiti.import("./project-trust-repository.ts");
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "scratchpad-test-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return { root, path: scratchpadPath(null, root) };
}
test("global and opaque session identities cannot alias or escape; private files survive new readers", async (t) => {
  const { root, path } = fixture(t);
  const initial = readScratchpad(path);
  assert.equal(initial.text, "");
  const saved = await saveScratchpad(path, "notes\n你好 📝", initial.revision);
  assert.deepEqual(readScratchpad(path), saved);
  const session = scratchpadPath("../../global", root);
  assert.equal(dirname(session), dirname(path));
  assert.notEqual(session, path);
  assert.notEqual(scratchpadPath("null", root), path);
  await saveScratchpad(session, "local", initial.revision);
  assert.equal(readScratchpad(path).text, saved.text);
  assert.equal(readScratchpad(session).text, "local");
  if (process.platform !== "win32") {
    assert.equal(statSync(path).mode & 0o777, 0o600);
    assert.equal(statSync(dirname(path)).mode & 0o777, 0o700);
  }
  assert.throws(() => scratchpadPath("", root));
  assert.throws(() => scratchpadPath("\0", root));
});
test("native project identities share registered worktrees without importing session notes or depending on trust markers", async (t) => {
  const { root, path: global } = fixture(t);
  const main = join(root, "repo"), linked = join(root, "linked"), other = join(root, "other"), plain = join(root, "plain");
  for (const folder of [main, other, plain]) mkdirSync(folder);
  const git = (cwd, ...args) => execFileSync("git", ["-C", cwd, ...args], { stdio: "pipe" });
  git(main, "init", "-qb", "main");
  git(main, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", "commit", "--allow-empty", "-qm", "fixture");
  git(main, "worktree", "add", "--detach", linked);
  git(other, "init", "-qb", "main");
  const project = scratchpadProject(main);
  assert.deepEqual(scratchpadProject(linked), project);
  assert.notEqual(scratchpadProject(other).projectId, project.projectId);
  assert.notEqual(scratchpadProject(plain).projectId, project.projectId);
  const alias = join(root, "alias"); symlinkSync(main, alias, "dir");
  assert.deepEqual(scratchpadProject(alias), project);
  const notePath = scratchpadPath({ projectId: project.projectId }, root);
  const legacy = scratchpadPath(project.projectId, root);
  const initial = readScratchpad(notePath);
  await saveScratchpad(global, "global stays", initial.revision);
  await saveScratchpad(legacy, "legacy stays", initial.revision);
  const legacyBytes = readFileSync(legacy, "utf8");
  assert.equal(readScratchpad(notePath).text, "", "no session-note import");
  await saveScratchpad(notePath, "shared project", initial.revision);
  assert.equal(readScratchpad(scratchpadPath({ projectId: scratchpadProject(linked).projectId }, root)).text, "shared project");
  writeFileSync(join(main, ".git", "brabbler-trust-id"), "11111111-1111-4111-8111-111111111111\n");
  assert.deepEqual(scratchpadProject(main), project, "trust changes never rename personal notes");
  writeFileSync(join(main, ".git", "brabbler-trust-id"), "malformed-marker\n");
  assert.deepEqual(scratchpadProject(linked), project, "malformed trust data cannot hide personal notes");
  assert.equal(trustedGitRepository(main), null, "trust consumers still refuse malformed markers");
  unlinkSync(join(main, ".git", "brabbler-trust-id"));
  symlinkSync(join(root, "missing-marker-target"), join(main, ".git", "brabbler-trust-id"));
  assert.deepEqual(scratchpadProject(main), project, "note identity never reads trust marker aliases");
  assert.equal(readFileSync(legacy, "utf8"), legacyBytes);
  assert.equal(readScratchpad(global).text, "global stays");
  assert.notEqual(notePath, legacy);
  assert.throws(() => scratchpadPath({ projectId: "../../escape" }, root));
  assert.throws(() => scratchpadPath({ projectId: project.projectId, sessionId: "legacy" }, root));
  assert.throws(() => scratchpadProject("relative"));
  const broken = join(root, "broken"); mkdirSync(broken); writeFileSync(join(broken, ".git"), "gitdir: /missing\n");
  assert.throws(() => scratchpadProject(broken), "failed Git identity must not fall back to a folder note");
});
test("serialized competing writes refuse stale versions, but a lost acknowledgement is idempotent", async (t) => {
  const { path } = fixture(t);
  const initial = readScratchpad(path);
  const results = await Promise.allSettled([saveScratchpad(path, "one", initial.revision), saveScratchpad(path, "two", initial.revision)]);
  assert.equal(results.filter((r) => r.status === "fulfilled").length, 1);
  const rejected = results.find((r) => r.status === "rejected");
  assert.ok(rejected.reason instanceof ScratchpadConflict);
  const current = readScratchpad(path);
  assert.deepEqual(await saveScratchpad(path, current.text, initial.revision), current);
  assert.deepEqual(rejected.reason.current, current);
  assert.equal((await saveScratchpad(path, "", current.revision)).text, "");
});
test("invalid/oversized edits and corrupt saved data are never overwritten", async (t) => {
  const { path } = fixture(t);
  const first = await saveScratchpad(path, "keep", readScratchpad(path).revision);
  await assert.rejects(saveScratchpad(path, "x".repeat(SCRATCHPAD_MAX_LENGTH + 1), first.revision));
  await assert.rejects(saveScratchpad(path, "no", "bad"));
  assert.equal(readScratchpad(path).text, "keep");
  writeFileSync(path, "{corrupt");
  assert.throws(() => readScratchpad(path));
  await assert.rejects(saveScratchpad(path, "replacement", first.revision));
  assert.equal(readFileSync(path, "utf8"), "{corrupt");
});
