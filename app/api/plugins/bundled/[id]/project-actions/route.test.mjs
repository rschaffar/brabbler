import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import test from "node:test";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url, { alias: { "@": process.cwd() } });
const collection = await jiti.import("./route.ts");
const operation = await jiti.import("./[operationId]/route.ts");
const reviews = await jiti.import("./[operationId]/reviews/[reviewId]/route.ts");
const { allowFileRoot } = await jiti.import("../../../../../../lib/file-access.ts");
const { updatePluginSettings } = await jiti.import("../../../../../../lib/plugins/settings.ts");
const { gitWorkflowManifest } = await jiti.import("../../../../../../plugins/git-workflow/manifest.ts");
const git = (cwd, ...args) => execFileSync("git", ["-C", cwd, "-c", "commit.gpgSign=false", ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
const params = (id = "git-workflow", other = {}) => ({ params: Promise.resolve({ id, ...other }) });
const req = (url, body, origin) => new Request(`http://localhost${url}`, { method: body === undefined ? "GET" : "POST", headers: { host: "localhost", ...(origin ? { origin } : {}), "content-type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "pi-project-action-route-test-")); const old = process.env.PI_CODING_AGENT_DIR; process.env.PI_CODING_AGENT_DIR = join(root, "agent");
  t.after(() => { if (old === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = old; rmSync(root, { recursive: true, force: true }); });
  const cwd = join(root, "repo"); git(root, "init", "-qb", "main", cwd); git(cwd, "config", "user.name", "Test"); git(cwd, "config", "user.email", "test@example.invalid");
  writeFileSync(join(cwd, "source"), "source"); git(cwd, "add", "."); git(cwd, "commit", "-qm", "Base"); git(cwd, "branch", "feature"); allowFileRoot(cwd);
  updatePluginSettings(gitWorkflowManifest, "global", cwd, { enabled: true }, []);
  updatePluginSettings(gitWorkflowManifest, "project", cwd, { targetBranch: "main", cleanupFeature: "allow" }, []);
  return { cwd, tip: git(cwd, "rev-parse", "HEAD") };
}
test("generic routes enforce origin/payload/owner boundaries and expose operation-bound history while disabled", async (t) => {
  const { cwd, tip } = fixture(t), base = "/api/plugins/bundled/git-workflow/project-actions";
  const input = { cwd, requestId: randomUUID(), action: "cleanup", payload: { featureBranch: "feature", featureTip: tip, integrationCommit: tip, targetBranch: "main", removeWorktree: false, deleteBranch: true } };
  assert.equal((await collection.POST(req(base, input, "https://hostile.invalid"), params())).status, 403);
  assert.equal((await collection.POST(req(base, { ...input, requestId: "invalid" }), params())).status, 400);
  assert.equal((await collection.POST(req(base, input), params("unknown"))).status, 400);
  const start = await collection.POST(req(base, input), params()); assert.equal(start.status, 202);
  const op = await start.json(), url = `${base}/${op.id}`, owner = params("git-workflow", { operationId: op.id });
  let status;
  const deadline = Date.now() + 10_000;
  do { status = await (await operation.GET(req(url), owner)).json(); if (status.state !== "preparing") break; assert.ok(Date.now() < deadline); await delay(10); } while (true);
  assert.equal(status.state, "review", JSON.stringify(status)); assert.equal(git(cwd, "rev-parse", "feature"), tip);
  assert.equal((await operation.POST(req(url, { cwd, decision: "force" }), owner)).status, 409);
  const reviewId = status.receipt.card.review.id, reviewOwner = params("git-workflow", { operationId: op.id, reviewId });
  assert.equal((await reviews.GET(req(status.reviewBaseUrl), reviewOwner)).status, 200);
  assert.equal((await reviews.GET(req(status.reviewBaseUrl), params("git-workflow", { operationId: op.id, reviewId: randomUUID() }))).status, 400);
  assert.equal((await reviews.GET(req(`${status.reviewBaseUrl}?download=1`), reviewOwner)).status, 200);
  assert.equal((await operation.POST(req(url, { cwd, decision: "reject" }), owner)).status, 200);
  do { status = await (await operation.GET(req(url), owner)).json(); if (status.state === "cancelled") break; assert.ok(Date.now() < deadline); await delay(10); } while (true);
  updatePluginSettings(gitWorkflowManifest, "global", cwd, { enabled: false }, []);
  assert.equal((await reviews.GET(req(status.reviewBaseUrl), reviewOwner)).status, 200);
  const listed = await collection.GET(req(`${base}?${new URLSearchParams({ cwd })}`), params()); assert.equal(listed.status, 200); assert.equal((await listed.json()).enabled, false);
  assert.equal(git(cwd, "rev-parse", "feature"), tip);
});
