import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import test from "node:test";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url, { alias: { "@": process.cwd() }, interopDefault: true, moduleCache: false });
const { GET, PUT } = await jiti.import("./service.ts");
const { SessionManager } = await jiti.import("@earendil-works/pi-coding-agent");
const { allowFileRoot } = await jiti.import("../../../../lib/file-access.ts");
const exec = promisify(execFile);
test("browser authorization route: scope selectors, independent CAS and live revocation", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "pi-web-auth-api-")), repo = join(root, "repo");
  t.after(() => rm(root, { recursive: true, force: true }));
  await exec("git", ["init", "-qb", "main", repo], { env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: join(root, "no-config") } });
  await exec("git", ["-C", repo, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "--allow-empty", "-qm", "initial"],
    { env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: join(root, "no-config") } });
  allowFileRoot(repo);
  const prior = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = join(root, "agent");
  t.after(() => { if (prior === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = prior; });
  const get = (scope, extra = "") => GET(new Request(`http://localhost/api/git/authorizations?scope=${scope}${extra}`));
  const put = (input) => PUT(new Request("http://localhost/api/git/authorizations", { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify(input) }));
  const g = await (await get("global")).json();
  assert.equal(g.actions.commit.effective, "none");
  assert.equal(g.approvalToken, false);
  assert.equal((await get("global", `&repositoryPath=${encodeURIComponent(repo)}`)).status, 400);
  assert.equal((await get("project")).status, 400);
  const pg = { scope: "global", action: "commit", decision: "allow", revision: g.revision, policyRevision: g.policyRevision };
  const allowed = await (await put(pg)).json();
  assert.equal(allowed.actions.commit.effective, "allow");
  assert.equal((await put(pg)).status, 409);
  const query = `&repositoryPath=${encodeURIComponent(repo)}`;
  const p = await (await get("project", query)).json();
  assert.equal(p.actions.commit.effective, "allow");
  assert.equal(p.actions.commit.session, "inherit");
  const denied = await (await put({ scope: "project", repositoryPath: repo, action: "commit", decision: "deny",
    revision: p.revision, policyRevision: p.policyRevision })).json();
  assert.equal(denied.actions.commit.effective, "deny");
  assert.equal((await (await get("global")).json()).actions.commit.effective, "allow");
  assert.equal((await (await get("project", query)).json()).actions.commit.effective, "deny");
  assert.equal((await put({ ...pg, revision: denied.revision, policyRevision: denied.policyRevision, modelProposal: true })).status, 400);
  assert.equal((await get("session", query)).status, 400);
  const chat = SessionManager.create(repo);
  chat.appendMessage({ role: "user", content: "chat", timestamp: Date.now() });
  chat.appendMessage({ role: "assistant", content: [{ type: "text", text: "ready" }], timestamp: Date.now() });
  const sessionId = chat.getSessionId();
  const session = await get("session", `${query}&sessionId=${sessionId}`);
  assert.equal(session.status, 200);
  const sessionBefore = await session.json();
  assert.equal(sessionBefore.actions.commit.effective, "deny");
  const sessionAllow = await put({ scope: "session", repositoryPath: repo, sessionId, action: "commit", decision: "allow",
    revision: sessionBefore.revision, policyRevision: sessionBefore.policyRevision });
  assert.equal(sessionAllow.status, 200);
  assert.equal((await sessionAllow.json()).actions.commit.effective, "allow");
  assert.equal((await (await get("project", query)).json()).actions.commit.effective, "deny");
});
